using AssetPass.Application.Common;
using AssetPass.Application.Interfaces;
using AssetPass.Domain.Entities;
using AssetPass.Domain.Enums;
using FluentValidation;

namespace AssetPass.Application.Features.Auth.Commands.RegisterTenant;

/// <summary>
/// Handles registration of a new company (tenant) and its initial Owner user.
///
/// Orchestration order:
/// 1. Validate command with FluentValidation.
/// 2. Ensure admin email is not already taken.
/// 3. Create and persist Tenant entity.
/// 4. Create and persist domain ApplicationUser entity.
/// 5. Create ASP.NET Core Identity user via IIdentityService.
/// 6. Link identity ID back to domain user.
/// 7. Commit everything.
///
/// Security: TenantId is generated server-side, never accepted from client input.
/// </summary>
public sealed class RegisterTenantCommandHandler
{
    private readonly IApplicationDbContext _db;
    private readonly IIdentityService _identityService;
    private readonly IValidator<RegisterTenantCommand> _validator;

    public RegisterTenantCommandHandler(
        IApplicationDbContext db,
        IIdentityService identityService,
        IValidator<RegisterTenantCommand> validator)
    {
        _db = db;
        _identityService = identityService;
        _validator = validator;
    }

    public async Task<Result<Guid>> HandleAsync(RegisterTenantCommand command, CancellationToken ct = default)
    {
        // 1. Validate
        var validation = await _validator.ValidateAsync(command, ct);
        if (!validation.IsValid)
        {
            var validationErrors = validation.Errors.Select(e => e.ErrorMessage).ToArray();
            return Result<Guid>.Failure(validationErrors);
        }

        // 2. Check for duplicate admin email
        var existing = await _identityService.FindByEmailAsync(command.AdminEmail, ct);
        if (existing is not null)
            return Result<Guid>.Failure("Ya existe una cuenta registrada con ese correo electrónico.");

        // 3. Create Tenant entity (Id is generated by BaseEntity constructor)
        var tenant = new Tenant
        {
            CommercialName = command.CommercialName.Trim(),
            LegalName = command.LegalName?.Trim(),
            Rnc = command.Rnc?.Trim(),
            Phone = command.Phone.Trim(),
            Email = command.CompanyEmail.Trim().ToLowerInvariant(),
            Address = command.Address?.Trim(),
            Currency = command.Currency.ToUpperInvariant(),
            TimeZone = command.TimeZone,
            SubscriptionStatus = SubscriptionStatus.Trial,
            TrialEndDate = DateTime.UtcNow.AddDays(14),
            IsActive = true
        };

        _db.Tenants.Add(tenant);

        // 4. Create domain ApplicationUser (linked to tenant)
        var domainUser = new ApplicationUser
        {
            TenantId = tenant.Id,
            FirstName = command.AdminFirstName.Trim(),
            LastName = command.AdminLastName.Trim(),
            Email = command.AdminEmail.Trim().ToLowerInvariant(),
            Role = UserRole.Owner,
            IsActive = true
        };

        _db.ApplicationUsers.Add(domainUser);

        // 5. Create Identity user via IIdentityService (no direct Identity dependency in Application)
        var (identityUserId, identityErrors) = await _identityService.CreateUserAsync(
            email: command.AdminEmail.Trim().ToLowerInvariant(),
            password: command.AdminPassword,
            tenantId: tenant.Id,
            applicationUserId: domainUser.Id,
            role: UserRole.Owner.ToString(),
            ct: ct);

        if (identityUserId is null)
            return Result<Guid>.Failure(identityErrors);

        // 6. Link identity ID back to domain user
        domainUser.IdentityUserId = identityUserId;

        // 7. Commit all changes in one transaction
        await _db.SaveChangesAsync(ct);

        return Result<Guid>.Success(tenant.Id);
    }
}
